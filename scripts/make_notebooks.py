    ap.add_argument("--out", type=Path, default=ROOT / "notebooks" / "kaggle")
    ap.add_argument("--repo-url", default=DEFAULT_REPO_URL)
    ap.add_argument("--git-ref", default=DEFAULT_GIT_REF)
    args = ap.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, nb in notebooks(args.repo_url, args.git_ref).items():
        path = args.out / f"{name}.ipynb"
        path.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n")
        paths.append(path)
        print(path)
    return paths


