def _py(v) -> str:
    if isinstance(v, (bool, type(None))):
        return repr(v)
    return json.dumps(v)


def params_cell(repo_url: str, git_ref: str, extra: list[tuple[str, object, str]]) -> str:
    rows = [
        ("REPO_URL", repo_url, "the HookSeq repo (public: no token needed; GITHUB_TOKEN only for a private fork)"),
        ("GIT_REF", git_ref, "branch or tag to run (pinned to the release tag of the reported runs)"),
        ("SIZE", "50m", "Yambda size: '50m' or '500m'"),
        *extra,
    ]
    lines = [
        "# Parameters: the defaults work unedited (attach inputs, then Save Version ->",
        "# Save & Run All). Generated by scripts/make_notebooks.py.",
    ]
    lines += [f"{n} = {_py(v)}  # {c}" for n, v, c in rows]
    lines += [
        "",
        "# fixed Kaggle paths",
        'INPUT_ROOT = "/kaggle/input"',
        'WORK = "/kaggle/working"',
        'OUT = "/kaggle/working/out"',
        'REPO = "/kaggle/working/repo"',
        "",
        "import os",
        "import time",
        "",
        "# train.max_hours is measured from here (the session start), not from the script start",
        'os.environ.setdefault("HOOKREC_SESSION_START", str(int(time.time())))',
        'print("HOOKREC_SESSION_START =", os.environ["HOOKREC_SESSION_START"])',
    ]
    return "\n".join(lines)


