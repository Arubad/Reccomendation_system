def _nb(md: str, cells: list[str], accel: dict) -> dict:
    def code(src: str) -> dict:
        lines = src.strip("\n").split("\n")
        return {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": [ln + "\n" for ln in lines[:-1]] + lines[-1:],
        }

    md_lines = md.strip("\n").split("\n")
    md_cell = {
        "cell_type": "markdown",
        "metadata": {},
        "source": [ln + "\n" for ln in md_lines[:-1]] + md_lines[-1:],
    }
    return {
        "cells": [md_cell, *(code(c) for c in cells)],
        "metadata": {
            "kaggle": {
                "accelerator": accel["accelerator"],
                "dataSources": [],
                "isGpuEnabled": accel["isGpuEnabled"],
                "isInternetEnabled": True,
                "language": "python",
                "sourceType": "notebook",
            },
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 4,
    }


